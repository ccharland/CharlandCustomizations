function Invoke-CHAREC2ProcessScan {
    <#
    .SYNOPSIS
        Runs a process-name scan on EC2 instances through SSM Run Command.
    .DESCRIPTION
        Shared engine for Find-CHAREC2Process and Find-CHAREC2MissingProcess. Looks up each
        instance's platform in SSM, sends a per-platform script, polls for results, and
        returns one object per instance that was checked successfully. Instances that are
        not SSM online, or whose command fails or times out, are warned about and omitted,
        so callers can tell "process absent" apart from "could not check".
        Not exported from the module.
    .PARAMETER InstanceId
        EC2 instance IDs to scan.
    .PARAMETER LinuxProcess
        Process names to look for on Linux instances.
    .PARAMETER WindowsProcess
        Process names to look for on Windows instances (".exe" suffix is ignored).
    .PARAMETER TimeoutSeconds
        Maximum time to wait for each batch of commands.
    .PARAMETER AwsParam
        Hashtable of AWS common parameters (from New-AWSParamSplat) to splat to SSM cmdlets.
    .OUTPUTS
        PSCustomObject with InstanceId, Requested (names searched for) and Found (names seen).
    .NOTES
        Generated by Kiro using Auto, reviewed by ccharland
    #>
    [CmdletBinding()]
    [OutputType([PSCustomObject])]
    param(
        [Parameter(Mandatory)]
        [string[]]$InstanceId,
        [string[]]$LinuxProcess,
        [string[]]$WindowsProcess,
        [int]$TimeoutSeconds = 120,
        [hashtable]$AwsParam = @{}
    )
    # SSM accepts at most 50 targets per SendCommand call
    $maxTargetsPerCall = 50
    $pollIntervalSeconds = 3
    $terminalStatuses = @('Success', 'Failed', 'Cancelled', 'TimedOut', 'Cancelling')
    $uniqueIds = @($InstanceId | Select-Object -Unique)
    # Sort instances by platform using SSM inventory; unmanaged instances cannot be queried
    $platformById = @{}
    for ($i = 0; $i -lt $uniqueIds.Count; $i += $maxTargetsPerCall) {
        $chunk = $uniqueIds[$i..([Math]::Min($i + $maxTargetsPerCall, $uniqueIds.Count) - 1)]
        $filter = [Amazon.SimpleSystemsManagement.Model.InstanceInformationStringFilter]::new()
        $filter.Key = 'InstanceIds'
        $filter.Values = [System.Collections.Generic.List[string]]$chunk
        foreach ($info in @(Get-SSMInstanceInformation -Filter $filter @AwsParam)) {
            if ($info.PingStatus -eq 'Online') { $platformById[$info.InstanceId] = [string]$info.PlatformType }
        }
    }
    foreach ($id in $uniqueIds) {
        if (-not $platformById.ContainsKey($id)) {
            Write-Warning "Instance $id is not SSM managed/online. Skipping."
        }
    }
    $plan = @(
        @{ Platform = 'Linux';   Document = 'AWS-RunShellScript';      Names = @($LinuxProcess) }
        @{ Platform = 'Windows'; Document = 'AWS-RunPowerShellScript'; Names = @($WindowsProcess) }
    )
    foreach ($entry in $plan) {
        $targets = @($uniqueIds | Where-Object { $platformById[$_] -eq $entry.Platform })
        if ($targets.Count -eq 0) { continue }
        $names = @($entry.Names | Where-Object { $_ })
        if ($names.Count -eq 0) {
            Write-Verbose "No $($entry.Platform) process list supplied. Skipping $($targets.Count) instance(s)."
            continue
        }
        # Scripts are built only here, once the name list is known to be non-empty
        if ($entry.Platform -eq 'Linux') {
            $requested = $names
            # Names are compared as strings: awk would otherwise treat "0123" and "123" as equal
            $script = @(
                'snap=$(ps -eo comm=,args= 2>/dev/null)'
                ('for p in {0}; do' -f (($names | ForEach-Object { "'$_'" }) -join ' '))
                '  if printf ''%s\n'' "$snap" | awk -v p="$p" ''{n=split($2,a,"/"); if (($1 "")==(p "") || (a[n] "")==(p "")) f=1} END{exit !f}''; then'
                '    echo "$p"'
                '  fi'
                'done'
            )
            $comparison = [StringComparison]::Ordinal
        }
        else {
            $requested = @($names | ForEach-Object { $_ -replace '(?i)\.exe$', '' })
            $script = @(
                ('$names = @({0})' -f (($requested | ForEach-Object { "'$_'" }) -join ','))
                'foreach ($n in $names) {'
                '    if (Get-Process -Name $n -ErrorAction SilentlyContinue) { Write-Output $n }'
                '}'
            )
            $comparison = [StringComparison]::OrdinalIgnoreCase
        }
        for ($i = 0; $i -lt $targets.Count; $i += $maxTargetsPerCall) {
            $batch = @($targets[$i..([Math]::Min($i + $maxTargetsPerCall, $targets.Count) - 1)])
            # Start the clock before submitting so slow API calls don't shrink the polling window
            $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
            try {
                $command = Send-SSMCommand -InstanceId $batch -DocumentName $entry.Document `
                    -Parameter @{ commands = [string[]]$script } `
                    -Comment 'Find-CHAREC2Process' -TimeoutSecond $TimeoutSeconds @AwsParam -ErrorAction Stop
            }
            catch {
                # Callers may run with ErrorAction=Stop (Invoke-CHARScriptMultiRegionProfile);
                # one failed batch must not abort the remaining batches or platforms
                Write-Warning "Could not send command to $($batch -join ', '): $($_.Exception.Message). Skipping."
                continue
            }
            $pending = [System.Collections.Generic.List[string]]$batch
            while ($pending.Count -gt 0 -and (Get-Date) -lt $deadline) {
                Start-Sleep -Seconds $pollIntervalSeconds
                foreach ($id in @($pending)) {
                    try {
                        $inv = Get-SSMCommandInvocation -CommandId $command.CommandId -InstanceId $id -Detail $true @AwsParam -ErrorAction Stop
                    }
                    catch {
                        # Invocation record can lag behind SendCommand; retry on next poll
                        if ($_.Exception.Message -match 'InvocationDoesNotExist') { continue }
                        Write-Warning "Could not read result for ${id}: $($_.Exception.Message)"
                        [void]$pending.Remove($id)
                        continue
                    }
                    if ($inv.Status.Value -notin $terminalStatuses) { continue }
                    [void]$pending.Remove($id)
                    if ($inv.Status.Value -ne 'Success') {
                        Write-Warning "Command on $id ended with status $($inv.Status.Value). Skipping."
                        continue
                    }
                    $output = ($inv.CommandPlugins | ForEach-Object { $_.Output }) -join "`n"
                    $seen = @($output -split '\r?\n' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
                    $foundNames = @($requested | Where-Object {
                            $name = $_
                            $seen | Where-Object { $_.Equals($name, $comparison) }
                        })
                    [PSCustomObject]@{ InstanceId = $id; Requested = $requested; Found = $foundNames }
                }
            }
            foreach ($id in $pending) {
                Write-Warning "Timed out waiting for command result from $id."
            }
        }
    }
}

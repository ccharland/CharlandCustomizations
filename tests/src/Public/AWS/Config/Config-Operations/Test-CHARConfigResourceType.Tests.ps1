            function New-RandomInvalidInput {
                <#
                .SYNOPSIS
                    Generates inputs guaranteed to be rejected by the validator.
                .DESCRIPTION
                    Produces strings that cannot be corrected to a valid AWS Config resource
                    type: special characters in segments, digit-leading segments, too few
                    segments, and empty/null-like values.
                .PARAMETER Count
                    Number of invalid inputs to generate.
                #>
                [CmdletBinding()]
                param(
                    [Parameter()]
                    [int]$Count = 100
                )

                $specialChars = @('!', '@', '#', '$', '%', '^', '&', '*', '(', ')', ' ', '+', '=', '?', '<', '>', '/', '\', '|', '{', '}', '[', ']', '~')
                $validSegments = @('EC2', 'S3', 'Lambda', 'RDS', 'IAM', 'DynamoDB', 'SNS', 'SQS', 'ECS', 'EKS')
                $validResources = @('Instance', 'Bucket', 'Function', 'DBInstance', 'Role', 'Table', 'Topic', 'Queue', 'Cluster', 'Service')
                $random = [System.Random]::new()
                $results = [System.Collections.Generic.List[string]]::new($Count)

                # Category 1: Segments with special characters (~33% of output)
                $specialCharCount = [math]::Ceiling($Count * 0.33)
                for ($i = 0; $i -lt $specialCharCount; $i++) {
                    $char = $specialChars[$random.Next(0, $specialChars.Count)]
                    $segment = $validSegments[$random.Next(0, $validSegments.Count)]
                    $resource = $validResources[$random.Next(0, $validResources.Count)]
                    # Insert special char at random position within the resource segment
                    $pos = $random.Next(1, $resource.Length)
                    $badResource = $resource.Insert($pos, $char)
                    $results.Add("AWS::${segment}::${badResource}")
                }

                # Category 2: Segments beginning with digits (~22% of output)
                $digitCount = [math]::Ceiling($Count * 0.22)
                for ($i = 0; $i -lt $digitCount; $i++) {
                    $digit = $random.Next(0, 10)
                    $segment = $validSegments[$random.Next(0, $validSegments.Count)]
                    $resource = $validResources[$random.Next(0, $validResources.Count)]
                    # Randomly put digit-leading in service or resource position
                    if ($random.Next(0, 2) -eq 0) {
                        $results.Add("AWS::${digit}${segment}::${resource}")
                    }
                    else {
                        $results.Add("AWS::${segment}::${digit}${resource}")
                    }
                }

                # Category 3: Too few segments after prefix (~22% of output)
                $fewSegCount = [math]::Ceiling($Count * 0.22)
                for ($i = 0; $i -lt $fewSegCount; $i++) {
                    $segment = $validSegments[$random.Next(0, $validSegments.Count)]
                    $variant = $random.Next(0, 3)
                    switch ($variant) {
                        0 { $results.Add("AWS::${segment}") }            # Only one segment after AWS::
                        1 { $results.Add($segment) }                      # Single word, no separators
                        2 { $results.Add("${segment}Something") }         # Concatenated, no separators
                    }
                }

                # Category 4: Empty/null-like and garbage (~23% of output)
                $garbageCount = $Count - $specialCharCount - $digitCount - $fewSegCount
                $garbagePool = @(
                    '',
                    '   ',
                    '      ',
                    '!@#$%',
                    ':::',
                    '::::',
                    'AWS::!!::##',
                    'AWS::::Instance',
                    '::EC2::Instance',
                    'AWS::EC2::',
                    'AWS::::',
                    '!!invalid!!',
                    '12345',
                    '....',
                    'AWS::  ::  ',
                    'AWS:: EC2:: Instance',
                    'A W S :: E C 2 :: I n s t a n c e'
                )
                for ($i = 0; $i -lt $garbageCount; $i++) {
                    $results.Add($garbagePool[$random.Next(0, $garbagePool.Count)])
                }

                return $results.ToArray()
            }
        }


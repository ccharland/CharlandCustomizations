            function New-RandomCaseVariant {
                <#
                .SYNOPSIS
                    Generates random case variants of a given resource type string.
                .DESCRIPTION
                    For a given input string, produces Count random case variants by
                    randomly toggling the case of each character. Ensures at least one
                    character differs from the original in each variant.
                .PARAMETER InputString
                    The source resource type string to generate variants of.
                .PARAMETER Count
                    Number of case variants to generate.
                #>
                [CmdletBinding()]
                param(
                    [Parameter(Mandatory)]
                    [string]$InputString,

                    [Parameter()]
                    [int]$Count = 10
                )

                $random = [System.Random]::new()
                $results = [System.Collections.Generic.List[string]]::new($Count)

                for ($i = 0; $i -lt $Count; $i++) {
                    $attempts = 0
                    do {
                        $variant = -join ($InputString.ToCharArray() | ForEach-Object {
                            if ($random.Next(0, 2) -eq 0) {
                                [char]::ToLower($_)
                            }
                            else {
                                [char]::ToUpper($_)
                            }
                        })
                        $attempts++
                        # Ensure at least one char differs from original (avoid identical output)
                    } while ($variant -ceq $InputString -and $attempts -lt 20)

                    # Fallback: if we couldn't differ, just lowercase the whole thing
                    if ($variant -ceq $InputString) {
                        $variant = $InputString.ToLower()
                    }

                    $results.Add($variant)
                }

                return $results.ToArray()
            }
        }


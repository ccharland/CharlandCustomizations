                    }
                )
            } -ModuleName 'Config-Operations'
        }

        It 'Accepts ResourceId from pipeline input' {
            $results = 'i-0123456789abcdef0' | Get-CHARConfigResourceComplianceReport -ResourceType 'AWS::EC2::Instance'
            $results | Should -Not -BeNullOrEmpty
            $results.ResourceId | Should -Be 'i-0123456789abcdef0'
        }
    }

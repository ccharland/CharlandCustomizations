Describe 'Get-CHARConfigResourceComplianceReport' -Tag 'Unit' {

    BeforeAll {
        Mock Test-CHARAWSCmdlet { } -ModuleName 'Config-Operations'
        Mock New-AWSParamSplat { return @{} } -ModuleName 'Config-Operations'
        Mock Test-CHARConfigResourceType { return $ResourceType } -ModuleName 'Config-Operations'
    }

    Context 'Happy path - evaluations returned' {

        BeforeAll {
            Mock Get-CFGComplianceDetailsByResource {
                @(
                    [PSCustomObject]@{
                        EvaluationResultIdentifier = [PSCustomObject]@{
                            EvaluationResultQualifier = [PSCustomObject]@{
                                ConfigRuleName = 'ec2-instance-managed-by-ssm'
                            }
                        }
                        ComplianceType     = 'COMPLIANT'
                        ResultRecordedTime = [datetime]'2024-06-01 12:00:00'
                    },
                    [PSCustomObject]@{
                        EvaluationResultIdentifier = [PSCustomObject]@{
                            EvaluationResultQualifier = [PSCustomObject]@{
                                ConfigRuleName = 'ec2-security-group-attached-to-eni'
                            }
                        }
                        ComplianceType     = 'NON_COMPLIANT'
                        ResultRecordedTime = [datetime]'2024-06-01 12:05:00'
                    }
                )
            } -ModuleName 'Config-Operations'
        }

        It 'Emits one PSCustomObject per rule evaluation' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $results | Should -HaveCount 2
        }

        It 'Output objects have correct properties in order' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $expectedProperties = @('ResourceId', 'ResourceType', 'ConfigRuleName', 'ComplianceType', 'LastEvaluatedTime')
            $results[0].PSObject.Properties.Name | Should -Be $expectedProperties
        }

        It 'Sets ResourceId from function parameter' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $results[0].ResourceId | Should -Be 'i-0123456789abcdef0'
            $results[1].ResourceId | Should -Be 'i-0123456789abcdef0'
        }

        It 'Sets ResourceType from function parameter' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $results[0].ResourceType | Should -Be 'AWS::EC2::Instance'
            $results[1].ResourceType | Should -Be 'AWS::EC2::Instance'
        }

        It 'Extracts ConfigRuleName from nested evaluation result' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $results[0].ConfigRuleName | Should -Be 'ec2-instance-managed-by-ssm'
            $results[1].ConfigRuleName | Should -Be 'ec2-security-group-attached-to-eni'
        }

        It 'Maps ComplianceType from evaluation result' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $results[0].ComplianceType | Should -Be 'COMPLIANT'
            $results[1].ComplianceType | Should -Be 'NON_COMPLIANT'
        }

        It 'Maps LastEvaluatedTime from ResultRecordedTime' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $results[0].LastEvaluatedTime | Should -Be ([datetime]'2024-06-01 12:00:00')
            $results[1].LastEvaluatedTime | Should -Be ([datetime]'2024-06-01 12:05:00')
        }
    }

    Context 'No evaluations (Write-Warning)' {

        BeforeAll {
            Mock Get-CFGComplianceDetailsByResource {
                return @()
            } -ModuleName 'Config-Operations'
        }

        It 'Returns empty collection when no evaluations exist' {
            $results = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            $results | Should -BeNullOrEmpty
        }

        It 'Emits a warning containing the resource identifier' {
            $warning = Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance' 3>&1
            $warning | Should -Not -BeNullOrEmpty
            "$warning" | Should -BeLike "*i-0123456789abcdef0*"
        }
    }

    Context 'AccessDenied error' {

        BeforeAll {
            Mock Get-CFGComplianceDetailsByResource {
                throw [System.Exception]::new('User: arn:aws:iam::123456789012:user/test is not authorized to perform: config:GetComplianceDetailsByResource (AccessDenied)')
            } -ModuleName 'Config-Operations'
        }

        It 'Emits Write-Error on AccessDenied' {
            # Function sets $ErrorActionPreference = 'Stop' internally, so Write-Error becomes terminating
            $err = $null
            try {
                Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            }
            catch {
                $err = $_
            }
            $err | Should -Not -BeNullOrEmpty
            $err.Exception.Message | Should -BeLike "*Access denied*"
        }

        It 'Error message contains the resource identifier' {
            $err = $null
            try {
                Get-CHARConfigResourceComplianceReport -ResourceId 'i-0123456789abcdef0' -ResourceType 'AWS::EC2::Instance'
            }
            catch {
                $err = $_
            }
            $err.Exception.Message | Should -BeLike "*i-0123456789abcdef0*"
        }
    }


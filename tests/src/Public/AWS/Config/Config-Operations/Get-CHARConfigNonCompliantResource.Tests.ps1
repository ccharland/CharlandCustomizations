BeforeAll {
    Get-Module Config-Operations -All | Remove-Module -Force -ErrorAction SilentlyContinue
    $modulePath = Resolve-Path "$PSScriptRoot/../../../../../../src/CharlandCustomizations/Public/AWS/Config/Config-Operations.psm1"
    Import-Module $modulePath -Force
}

Describe 'Get-CHARConfigNonCompliantResource' -Tag 'Unit' {

    BeforeAll {
        Mock Test-CHARAWSCmdlet { } -ModuleName 'Config-Operations'
        Mock New-AWSParamSplat { return @{} } -ModuleName 'Config-Operations'

        # Define the custom exception type for NoSuchConfigRuleException
        if (-not ('NoSuchConfigRuleException' -as [type])) {
            Add-Type -TypeDefinition 'public class NoSuchConfigRuleException : System.Exception { public NoSuchConfigRuleException(string message) : base(message) { } }'
        }
    }

    Context 'Happy path - non-compliant resources found' {

        BeforeAll {
            Mock Get-CFGComplianceDetailsByConfigRule {
                @(
                    [PSCustomObject]@{
                        EvaluationResultIdentifier = [PSCustomObject]@{
                            EvaluationResultQualifier = [PSCustomObject]@{
                                ResourceId   = 'bucket-1'
                                ResourceType = 'AWS::S3::Bucket'
                            }
                        }
                        ComplianceType = 'NON_COMPLIANT'
                    },
                    [PSCustomObject]@{
                        EvaluationResultIdentifier = [PSCustomObject]@{
                            EvaluationResultQualifier = [PSCustomObject]@{
                                ResourceId   = 'bucket-2'
                                ResourceType = 'AWS::S3::Bucket'
                            }
                        }
                        ComplianceType = 'NON_COMPLIANT'
                    }
                )
            } -ModuleName 'Config-Operations'
        }

        It 'Returns collection of non-compliant resources with correct properties' {
            $results = Get-CHARConfigNonCompliantResource -ConfigRuleName 's3-bucket-versioning-enabled'

            $results | Should -HaveCount 2
            $results[0].ResourceId | Should -Be 'bucket-1'
            $results[0].ResourceType | Should -Be 'AWS::S3::Bucket'
            $results[0].ComplianceType | Should -Be 'NON_COMPLIANT'
            $results[0].ConfigRuleName | Should -Be 's3-bucket-versioning-enabled'
        }

        It 'Output objects have correct property order' {
            $results = Get-CHARConfigNonCompliantResource -ConfigRuleName 's3-bucket-versioning-enabled'

            $expectedOrder = @('ResourceId', 'ResourceType', 'ComplianceType', 'ConfigRuleName')
            $results[0].PSObject.Properties.Name | Should -Be $expectedOrder
        }

        It 'Emits each object individually to the pipeline' {
            $count = 0
            Get-CHARConfigNonCompliantResource -ConfigRuleName 's3-bucket-versioning-enabled' |
                ForEach-Object { $count++ }

            $count | Should -Be 2
        }

        It 'Calls Get-CFGComplianceDetailsByConfigRule with correct parameters' {
            Get-CHARConfigNonCompliantResource -ConfigRuleName 's3-bucket-versioning-enabled'

            Should -Invoke Get-CFGComplianceDetailsByConfigRule -ModuleName 'Config-Operations' -ParameterFilter {
                $ConfigRuleName -eq 's3-bucket-versioning-enabled' -and $ComplianceType -eq 'NON_COMPLIANT'
            }
        }
    }

    Context 'No non-compliant resources (full compliance)' {

        BeforeAll {
            Mock Get-CFGComplianceDetailsByConfigRule {
                return @()
            } -ModuleName 'Config-Operations'
        }

        It 'Emits no output when rule has zero non-compliant resources' {
            $results = Get-CHARConfigNonCompliantResource -ConfigRuleName 's3-bucket-versioning-enabled'

            $results | Should -BeNullOrEmpty
        }

        It 'Writes verbose message indicating full compliance' {
            $verboseOutput = Get-CHARConfigNonCompliantResource -ConfigRuleName 's3-bucket-versioning-enabled' -Verbose 4>&1 |
                Where-Object { $_ -is [System.Management.Automation.VerboseRecord] }

            $verboseOutput | Should -Not -BeNullOrEmpty
            ($verboseOutput | Where-Object { $_.Message -match 'no non-compliant resources.*compliant' }) | Should -Not -BeNullOrEmpty
        }
    }

    Context 'NoSuchConfigRuleException' {

        BeforeAll {
            Mock Get-CFGComplianceDetailsByConfigRule {
                throw [NoSuchConfigRuleException]::new("Config rule 'nonexistent-rule' does not exist.")
            } -ModuleName 'Config-Operations'
        }

        It 'Emits Write-Error when Config rule does not exist' {
            # The function sets ErrorActionPreference = 'Stop' internally, so
            # Write-Error becomes terminating. Capture via redirect to confirm error content.
            $err = $null
            try {
                Get-CHARConfigNonCompliantResource -ConfigRuleName 'nonexistent-rule' -ErrorVariable err -ErrorAction Stop
            }
            catch {
                $err = $_
            }

            $err | Should -Not -BeNullOrEmpty
            $err.Exception.Message | Should -BeLike "*nonexistent-rule*"
        }
    }

    Context 'Pipeline input' {

        BeforeAll {
            Mock Get-CFGComplianceDetailsByConfigRule {
                @(
                    [PSCustomObject]@{
                        EvaluationResultIdentifier = [PSCustomObject]@{
                            EvaluationResultQualifier = [PSCustomObject]@{
                                ResourceId   = 'instance-1'
                                ResourceType = 'AWS::EC2::Instance'
                            }
                        }
                        ComplianceType = 'NON_COMPLIANT'
                    }
                )
            } -ModuleName 'Config-Operations'
        }

        It 'Accepts ConfigRuleName from pipeline input' {
            $results = 'ec2-instance-managed-by-ssm' | Get-CHARConfigNonCompliantResource

            $results | Should -Not -BeNullOrEmpty
            $results.ConfigRuleName | Should -Be 'ec2-instance-managed-by-ssm'
        }

        It 'Processes multiple pipeline values' {
            $results = @('rule-one', 'rule-two') | Get-CHARConfigNonCompliantResource

            $results | Should -HaveCount 2
        }
    }
}

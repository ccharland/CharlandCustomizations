Describe 'Get-CHARKMSKeyLastUsage' -Tag 'Unit', 'Help' {

    It 'Has comment-based help with an example and the safe-to-delete caveat' {
        $help = Get-Help Get-CHARKMSKeyLastUsage -Full
        $help.Examples.Example.Count | Should -BeGreaterThan 0
        ($help.Description.Text -join ' ') | Should -Match 'safe to delete'
    }

    It 'Reports Observed when a last usage record exists' {
        Mock Get-KMSKeyLastUsage {
            [PSCustomObject]@{
                KeyCreationDate   = [datetime]'2020-01-01'
                TrackingStartDate = [datetime]'2024-01-01'
                KeyLastUsage      = [PSCustomObject]@{ Operation = 'Decrypt'; Timestamp = [datetime]'2025-05-05'; CloudTrailEventId = 'evt-1' }
            }
        } -ModuleName KMS-Customizations
        $r = Get-CHARKMSKeyLastUsage -KeyArn $script:keyArn
        $r.UsageStatus | Should -Be 'Observed'
        $r.LastUsedOperation | Should -Be 'Decrypt'
        $r.CloudTrailEventId | Should -Be 'evt-1'
        $r.KeyId | Should -Be $script:keyId
        Should -Invoke Get-KMSKeyLastUsage -ModuleName KMS-Customizations -ParameterFilter { $KeyId -eq $script:keyId -and $Region -eq 'us-east-1' }
    }

    It 'Reports NeverUsedSinceCreation when created after tracking began and unused' {
        Mock Get-KMSKeyLastUsage {
            [PSCustomObject]@{ KeyCreationDate = [datetime]'2025-02-01'; TrackingStartDate = [datetime]'2024-01-01'; KeyLastUsage = $null }
        } -ModuleName KMS-Customizations
        $r = Get-CHARKMSKeyLastUsage -KeyArn $script:keyArn
        $r.UsageStatus | Should -Be 'NeverUsedSinceCreation'
        $r.LastUsedTimestamp | Should -BeNullOrEmpty
    }

    It 'Reports IncompleteHistory when the key predates tracking and has no record' {
        Mock Get-KMSKeyLastUsage {
            [PSCustomObject]@{ KeyCreationDate = [datetime]'2020-01-01'; TrackingStartDate = [datetime]'2024-01-01'; KeyLastUsage = $null }
        } -ModuleName KMS-Customizations
        (Get-CHARKMSKeyLastUsage -KeyArn $script:keyArn).UsageStatus | Should -Be 'IncompleteHistory'
    }

    It 'Throws for a malformed key ARN' {
        { Get-CHARKMSKeyLastUsage -KeyArn 'bad' } | Should -Throw '*Invalid KMS key ARN*'
    }


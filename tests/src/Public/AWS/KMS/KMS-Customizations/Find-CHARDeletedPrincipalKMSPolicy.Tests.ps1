Describe 'Find-CHARDeletedPrincipalKMSPolicy' -Tag 'Unit', 'Help' {

    BeforeAll {
        $script:policy = @{
            Version   = '2012-10-17'
            Statement = @(
                @{ Sid = 'Root'; Effect = 'Allow'; Principal = @{ AWS = 'arn:aws:iam::123456789012:root' }; Action = 'kms:*'; Resource = '*' }
                @{ Sid = 'Orphan'; Effect = 'Allow'; Principal = @{ AWS = @('AROAEXAMPLEDELETED1234', 'arn:aws:iam::123456789012:role/ok') }; Action = 'kms:Decrypt'; Resource = '*' }
                @{ Effect = 'Allow'; Principal = @{ AWS = 'AIDAEXAMPLEDELETED5678' }; Action = 'kms:Encrypt'; Resource = '*' }
                @{ Effect = 'Allow'; Principal = '*'; Action = 'kms:Describe*'; Resource = '*' }
            )
        } | ConvertTo-Json -Depth 10
    }

    It 'Has comment-based help with examples' {
        (Get-Help Find-CHARDeletedPrincipalKMSPolicy -Full).Examples.Example.Count | Should -BeGreaterThan 1
    }

    It 'Reports unresolved principal IDs for a single key' {
        Mock Get-KMSKeyPolicy { $script:policy } -ModuleName KMS-Customizations
        $r = @(Find-CHARDeletedPrincipalKMSPolicy -KeyArn $script:keyArn)
        $r.Count | Should -Be 2
        $r[0].DeletedPrincipal | Should -Be 'AROAEXAMPLEDELETED1234'
        $r[0].Statement | Should -Be 'Orphan'
        $r[1].Statement | Should -Be 'Statement[2]'
        $r[0].KeyId | Should -Be $script:keyId
        Should -Invoke Get-KMSKeyPolicy -ModuleName KMS-Customizations -ParameterFilter { $PolicyName -eq 'default' -and $Region -eq 'us-east-1' }
    }

    It 'Audits only customer-managed keys when no key is given' {
        Mock Get-KMSKeyList {
            @(
                [PSCustomObject]@{ KeyId = 'cust-1'; KeyArn = 'arn:aws:kms:us-east-1:123456789012:key/cust-1' }
                [PSCustomObject]@{ KeyId = 'aws-1'; KeyArn = 'arn:aws:kms:us-east-1:123456789012:key/aws-1' }
            )
        } -ModuleName KMS-Customizations
        Mock Get-KMSKey { [PSCustomObject]@{ KeyManager = if ($KeyId -eq 'cust-1') { 'CUSTOMER' } else { 'AWS' } } } -ModuleName KMS-Customizations
        Mock Get-KMSKeyPolicy { $script:policy } -ModuleName KMS-Customizations
        $r = @(Find-CHARDeletedPrincipalKMSPolicy -Region us-east-1)
        $r.Count | Should -Be 2
        Should -Invoke Get-KMSKeyPolicy -ModuleName KMS-Customizations -Times 1 -Exactly
    }

    It 'Returns nothing when all principals resolve' {
        Mock Get-KMSKeyPolicy {
            @{ Statement = @(@{ Effect = 'Allow'; Principal = @{ AWS = 'arn:aws:iam::123456789012:root' }; Action = 'kms:*' }) } | ConvertTo-Json -Depth 10
        } -ModuleName KMS-Customizations
        @(Find-CHARDeletedPrincipalKMSPolicy -KeyArn $script:keyArn).Count | Should -Be 0
    }

    It 'Warns and continues when a policy cannot be retrieved' {
        Mock Get-KMSKeyPolicy { throw 'AccessDenied' } -ModuleName KMS-Customizations
        $r = @(Find-CHARDeletedPrincipalKMSPolicy -KeyArn $script:keyArn -WarningVariable w -WarningAction SilentlyContinue)
        $r.Count | Should -Be 0
        $w | Should -Not -BeNullOrEmpty
    }

    It 'Throws for a malformed key ARN' {
        { Find-CHARDeletedPrincipalKMSPolicy -KeyArn 'bad' } | Should -Throw '*Invalid KMS key ARN*'
    }
}

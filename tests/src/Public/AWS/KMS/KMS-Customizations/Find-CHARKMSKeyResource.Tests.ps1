Describe 'Find-CHARKMSKeyResource' -Tag 'Unit', 'Help' {

    It 'Has comment-based help with synopsis, description, example and the safe-to-delete caveat' {
        $help = Get-Help Find-CHARKMSKeyResource -Full
        $help.Synopsis | Should -Not -BeNullOrEmpty
        $help.Examples.Example.Count | Should -BeGreaterThan 0
        ($help.Description.Text -join ' ') | Should -Match 'safe to delete'
    }

    Context 'Matching' {
        BeforeEach {
            Mock Get-KMSAliasList {
                @([PSCustomObject]@{ AliasName = 'alias/app'; AliasArn = 'arn:aws:kms:us-east-1:123456789012:alias/app' })
            } -ModuleName KMS-Customizations
            Mock Select-CFGResourceConfig {
                @(
                    '{"resourceId":"vol-1","resourceType":"AWS::EC2::Volume","arn":"arn:vol-1","awsRegion":"us-east-1","accountId":"123456789012","configuration":{"kmsKeyId":"arn:aws:kms:us-east-1:123456789012:key/1234abcd-12ab-34cd-56ef-1234567890ab"}}',
                    '{"resourceId":"q-1","resourceType":"AWS::SQS::Queue","awsRegion":"us-east-1","accountId":"123456789012","configuration":{"kmsMasterKeyId":"ALIAS/APP"}}',
                    '{"resourceId":"db-1","resourceType":"AWS::RDS::DBInstance","awsRegion":"us-east-1","accountId":"123456789012","configuration":{"kmsKeyId":"1234ABCD-12ab-34cd-56ef-1234567890ab"}}',
                    '{"resourceId":"other","resourceType":"AWS::EC2::Volume","awsRegion":"us-east-1","accountId":"123456789012","configuration":{"kmsKeyId":"arn:aws:kms:us-east-1:123456789012:key/ffffffff-0000-0000-0000-000000000000"}}'
                )
            } -ModuleName KMS-Customizations
        }

        It 'Matches key ARN, alias and key ID and ignores unrelated resources' {
            $result = @(Find-CHARKMSKeyResource -KeyArn $script:keyArn)
            $result.Count | Should -Be 3
            ($result | Where-Object ResourceId -eq 'vol-1').MatchedOn | Should -Be 'KeyArn'
            ($result | Where-Object ResourceId -eq 'q-1').MatchedOn | Should -Be 'AliasName'
            ($result | Where-Object ResourceId -eq 'db-1').MatchedOn | Should -Be 'KeyId'
            ($result | Where-Object ResourceId -eq 'vol-1').MatchedProperty | Should -Be 'configuration.kmsKeyId'
            $result[0].PSObject.TypeNames | Should -Contain 'AWS.KMS.KeyResource'
        }

        It 'Defaults the region from the key ARN' {
            Find-CHARKMSKeyResource -KeyArn $script:keyArn | Out-Null
            Should -Invoke Select-CFGResourceConfig -ModuleName KMS-Customizations -ParameterFilter { $Region -eq 'us-east-1' }
        }

        It 'Honors an explicit -Region and accepts pipeline input' {
            $script:keyArn | Find-CHARKMSKeyResource -Region eu-west-1 | Out-Null
            Should -Invoke Select-CFGResourceConfig -ModuleName KMS-Customizations -ParameterFilter { $Region -eq 'eu-west-1' }
        }
    }

    Context 'Empty and error paths' {
        It 'Returns nothing when no resource references the key' {
            Mock Get-KMSAliasList { @() } -ModuleName KMS-Customizations
            Mock Select-CFGResourceConfig { @() } -ModuleName KMS-Customizations
            @(Find-CHARKMSKeyResource -KeyArn $script:keyArn).Count | Should -Be 0
        }

        It 'Throws for a malformed key ARN' {
            { Find-CHARKMSKeyResource -KeyArn 'not-an-arn' } | Should -Throw '*Invalid KMS key ARN*'
        }
    }

Describe 'Remove-CHARExpiredELBListenerCertificate' -Tag 'Unit' {
    BeforeEach {
        Mock Test-CHARAWSCmdlet { $true } -ModuleName ELB-Customizations
        Mock Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations { }

        Mock Get-ELB2LoadBalancer -ModuleName ELB-Customizations {
            @(
                [PSCustomObject]@{ LoadBalancerName = 'prod-web'; LoadBalancerArn = 'arn:lb/prod-web' }
                [PSCustomObject]@{ LoadBalancerName = 'dev-web'; LoadBalancerArn = 'arn:lb/dev-web' }
            )
        }
        Mock Get-ELB2Listener -ModuleName ELB-Customizations {
            @(
                [PSCustomObject]@{ ListenerArn = "$LoadBalancerArn/https"; Port = 443; Protocol = 'HTTPS' }
                [PSCustomObject]@{ ListenerArn = "$LoadBalancerArn/http"; Port = 80; Protocol = 'HTTP' }
            )
        }
        # Per listener: default cert is valid, plus one expired-long-ago and one expired-recently extra cert.
        Mock Get-ELB2ListenerCertificate -ModuleName ELB-Customizations {
            @(
                [PSCustomObject]@{ CertificateArn = "arn:aws:acm:us-east-1:123456789012:certificate/valid-default"; IsDefault = $true }
                [PSCustomObject]@{ CertificateArn = "arn:aws:acm:us-east-1:123456789012:certificate/old-aaa"; IsDefault = $false }
                [PSCustomObject]@{ CertificateArn = "arn:aws:acm:us-east-1:123456789012:certificate/recent-bbb"; IsDefault = $false }
                [PSCustomObject]@{ CertificateArn = "arn:aws:acm:us-east-1:123456789012:certificate/valid-ccc"; IsDefault = $false }
            )
        }
        Mock Get-ACMCertificateDetail -ModuleName ELB-Customizations {
            $notAfter = switch -Wildcard ($CertificateArn) {
                '*/old-aaa'    { [DateTime]::UtcNow.AddDays(-200) }
                '*/recent-bbb' { [DateTime]::UtcNow.AddDays(-10) }
                '*/nodate-*'   { [DateTime]::MinValue }
                default        { [DateTime]::UtcNow.AddDays(90) }
            }
            [PSCustomObject]@{ CertificateArn = $CertificateArn; NotAfter = $notAfter }
        }
    }

    It 'removes expired non-default certificates from HTTPS listeners on every load balancer' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -Confirm:$false)
        $results.Count | Should -Be 4
        ($results | Where-Object Action -eq 'Removed').Count | Should -Be 4
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 4 -Exactly
    }

    It 'only reads certificates for HTTPS and TLS listeners' {
        $null = Remove-CHARExpiredELBListenerCertificate -Confirm:$false
        Should -Invoke Get-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 2 -Exactly
        Should -Invoke Get-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly -ParameterFilter {
            $ListenerArn -like '*/http'
        }
    }

    It 'reads TLS listeners on network load balancers' {
        Mock Get-ELB2Listener -ModuleName ELB-Customizations {
            [PSCustomObject]@{ ListenerArn = "$LoadBalancerArn/tls"; Port = 443; Protocol = 'TLS' }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -LoadBalancerName 'prod-web' -Confirm:$false)
        $results.Count | Should -Be 2
        $results[0].Protocol | Should -Be 'TLS'
    }

    It 'looks up each certificate in ACM only once across listeners' {
        $null = Remove-CHARExpiredELBListenerCertificate -Confirm:$false
        Should -Invoke Get-ACMCertificateDetail -ModuleName ELB-Customizations -Times 4 -Exactly
    }

    It 'queries ACM in the certificate region rather than the -Region value' {
        $null = Remove-CHARExpiredELBListenerCertificate -Region eu-west-1 -Confirm:$false
        Should -Invoke Get-ACMCertificateDetail -ModuleName ELB-Customizations -Times 4 -Exactly -ParameterFilter {
            $Region -eq 'us-east-1'
        }
    }

    It 'honors -DaysExpired as a minimum age' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -DaysExpired 90 -Confirm:$false)
        $results.Count | Should -Be 2
        $results.CertificateArn | Should -Not -Contain 'arn:aws:acm:us-east-1:123456789012:certificate/recent-bbb'
        $results.DaysSinceExpired | Should -BeGreaterOrEqual 199
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 2 -Exactly -ParameterFilter {
            $Certificate.CertificateArn -like '*/old-aaa'
        }
    }

    It 'matches -LoadBalancerName with wildcards' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -LoadBalancerName 'prod-*' -Confirm:$false)
        $results.LoadBalancerName | Select-Object -Unique | Should -Be 'prod-web'
        Should -Invoke Get-ELB2Listener -ModuleName ELB-Customizations -Times 1 -Exactly
    }

    It 'never removes a default certificate and warns instead' {
        Mock Get-ELB2ListenerCertificate -ModuleName ELB-Customizations {
            [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/old-aaa'; IsDefault = $true }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -LoadBalancerName 'prod-web' -Confirm:$false -WarningVariable warnings -WarningAction SilentlyContinue)
        $results.Count | Should -Be 1
        $results[0].Action | Should -Be 'DefaultCertificate'
        $results[0].IsDefault | Should -BeTrue
        $warnings | Should -Match 'default certificate'
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'skips non-ACM certificates and warns' {
        Mock Get-ELB2ListenerCertificate -ModuleName ELB-Customizations {
            [PSCustomObject]@{ CertificateArn = 'arn:aws:iam::123456789012:server-certificate/legacy'; IsDefault = $false }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -Confirm:$false -WarningVariable warnings -WarningAction SilentlyContinue)
        $results.Count | Should -Be 0
        $warnings | Should -Match 'not an ACM certificate'
        Should -Invoke Get-ACMCertificateDetail -ModuleName ELB-Customizations -Times 0 -Exactly
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'leaves certificates alone when the ACM lookup fails' {
        Mock Get-ACMCertificateDetail -ModuleName ELB-Customizations { throw 'ResourceNotFoundException' }
        $results = @(Remove-CHARExpiredELBListenerCertificate -Confirm:$false -WarningVariable warnings -WarningAction SilentlyContinue)
        $results.Count | Should -Be 0
        $warnings | Should -Match 'unable to read ACM certificate details'
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'leaves certificates alone when ACM reports no expiration date' {
        Mock Get-ELB2ListenerCertificate -ModuleName ELB-Customizations {
            [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/nodate-ddd'; IsDefault = $false }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -Confirm:$false)
        $results.Count | Should -Be 0
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'does not remove under -WhatIf and reports Action Skipped' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -LoadBalancerName 'prod-web' -WhatIf)
        $results.Count | Should -Be 2
        $results.Action | Select-Object -Unique | Should -Be 'Skipped'
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'returns nothing when no load balancer matches' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -LoadBalancerName 'zzz*' -Confirm:$false)
        $results.Count | Should -Be 0
        Should -Invoke Get-ELB2Listener -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'rejects a negative -DaysExpired' {
        { Remove-CHARExpiredELBListenerCertificate -DaysExpired -1 } | Should -Throw
    }

    It 'surfaces a terminating error when removal fails' {
        Mock Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations { throw 'AccessDenied' }
        { Remove-CHARExpiredELBListenerCertificate -LoadBalancerName 'prod-web' -Confirm:$false } |
            Should -Throw '*AccessDenied*'
    }

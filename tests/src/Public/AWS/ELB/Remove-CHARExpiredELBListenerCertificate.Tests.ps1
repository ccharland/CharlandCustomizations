Describe 'Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate' -Tag 'Unit' {
    BeforeEach {
        Mock Test-CHARAWSCmdlet { $true } -ModuleName ELB-Customizations
        Mock Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations { }
        Mock Edit-ELB2Listener -ModuleName ELB-Customizations { }
        # Real code builds an AWS SDK model object; the SDK type may not be loaded in CI.
        Mock New-Object -ModuleName ELB-Customizations { [PSCustomObject]@{ CertificateArn = $null } }

        Mock Get-ELB2LoadBalancer -ModuleName ELB-Customizations {
            [PSCustomObject]@{ LoadBalancerName = 'prod-web'; LoadBalancerArn = 'arn:lb/prod-web' }
        }
        Mock Get-ELB2Listener -ModuleName ELB-Customizations {
            [PSCustomObject]@{ ListenerArn = "$LoadBalancerArn/https"; Port = 443; Protocol = 'HTTPS' }
        }
        Mock Get-ELB2ListenerCertificate -ModuleName ELB-Customizations {
            [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/old-def'; IsDefault = $true }
        }
        Mock Get-ACMCertificateList -ModuleName ELB-Customizations {
            'old-def', 'wild', 'exact', 'partial', 'stale' | ForEach-Object {
                [PSCustomObject]@{ CertificateArn = "arn:aws:acm:us-east-1:123456789012:certificate/$_" }
            }
        }
        Mock Get-ACMCertificateDetail -ModuleName ELB-Customizations {
            $id = ($CertificateArn -split '/')[-1]
            $detail = switch ($id) {
                'old-def' { @('app.example.com', @('app.example.com', 'www.example.com'), -30) }
                'wild'    { @('*.example.com', @('*.example.com'), 90) }
                'exact'   { @('app.example.com', @('app.example.com', 'www.example.com'), 200) }
                'partial' { @('app.example.com', @('app.example.com'), 300) }
                'stale'   { @('app.example.com', @('app.example.com', 'www.example.com'), -5) }
            }
            [PSCustomObject]@{
                CertificateArn          = $CertificateArn
                DomainName              = $detail[0]
                SubjectAlternativeNames = $detail[1]
                NotAfter                = [DateTime]::UtcNow.AddDays($detail[2])
            }
        }
    }

    It 'replaces an expired default certificate with the covering certificate that expires last' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false)
        $results.Count | Should -Be 1
        $results[0].Action | Should -Be 'DefaultReplaced'
        $results[0].ReplacementCertificateArn | Should -Be 'arn:aws:acm:us-east-1:123456789012:certificate/exact'
        Should -Invoke Edit-ELB2Listener -ModuleName ELB-Customizations -Times 1 -Exactly -ParameterFilter {
            $ListenerArn -eq 'arn:lb/prod-web/https' -and $Certificate.CertificateArn -like '*/exact'
        }
    }

    It 'does not pick expired or partially covering certificates' {
        $null = Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false
        Should -Invoke Edit-ELB2Listener -ModuleName ELB-Customizations -Times 0 -Exactly -ParameterFilter {
            $Certificate.CertificateArn -like '*/partial' -or $Certificate.CertificateArn -like '*/stale'
        }
    }

    It 'accepts a single-label wildcard certificate as a replacement' {
        Mock Get-ACMCertificateList -ModuleName ELB-Customizations {
            'old-def', 'wild', 'partial' | ForEach-Object {
                [PSCustomObject]@{ CertificateArn = "arn:aws:acm:us-east-1:123456789012:certificate/$_" }
            }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false)
        $results[0].ReplacementCertificateArn | Should -BeLike '*/wild'
    }

    It 'does not let a wildcard cover a multi-label name' {
        Mock Get-ACMCertificateDetail -ModuleName ELB-Customizations {
            $id = ($CertificateArn -split '/')[-1]
            if ($id -eq 'old-def') {
                [PSCustomObject]@{ DomainName = 'a.b.example.com'; SubjectAlternativeNames = @('a.b.example.com'); NotAfter = [DateTime]::UtcNow.AddDays(-30) }
            }
            else {
                [PSCustomObject]@{ DomainName = '*.example.com'; SubjectAlternativeNames = @('*.example.com'); NotAfter = [DateTime]::UtcNow.AddDays(90) }
            }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false -WarningAction SilentlyContinue)
        $results[0].Action | Should -Be 'NoReplacementFound'
    }

    It 'removes the expired certificate when it is still attached after the swap' {
        $null = Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 1 -Exactly -ParameterFilter {
            $Certificate.CertificateArn -like '*/old-def'
        }
    }

    It 'does not call remove when the swap already detached the expired certificate' {
        # Mock bodies run in the module's script scope, so the counter lives there instead of globally.
        & (Get-Module ELB-Customizations) { $script:ElbTestListenerReads = 0 }
        Mock Get-ELB2ListenerCertificate -ModuleName ELB-Customizations {
            $script:ElbTestListenerReads++
            if ($script:ElbTestListenerReads -eq 1) {
                [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/old-def'; IsDefault = $true }
            }
            else {
                [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/exact'; IsDefault = $true }
            }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false)
        $results[0].Action | Should -Be 'DefaultReplaced'
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'leaves the listener unchanged without the switch' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -Confirm:$false -WarningAction SilentlyContinue)
        $results[0].Action | Should -Be 'DefaultCertificate'
        $results[0].ReplacementCertificateArn | Should -BeNullOrEmpty
        Should -Invoke Edit-ELB2Listener -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'reports NoReplacementFound and changes nothing when no certificate covers all names' {
        Mock Get-ACMCertificateList -ModuleName ELB-Customizations {
            'old-def', 'partial', 'stale' | ForEach-Object {
                [PSCustomObject]@{ CertificateArn = "arn:aws:acm:us-east-1:123456789012:certificate/$_" }
            }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false -WarningVariable warnings -WarningAction SilentlyContinue)
        $results[0].Action | Should -Be 'NoReplacementFound'
        $warnings | Should -Match 'no unexpired ISSUED ACM certificate covers'
        Should -Invoke Edit-ELB2Listener -ModuleName ELB-Customizations -Times 0 -Exactly
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'refuses to choose when two matches tie for the latest expiration' {
        Mock Get-ACMCertificateDetail -ModuleName ELB-Customizations {
            $id = ($CertificateArn -split '/')[-1]
            [PSCustomObject]@{
                DomainName              = 'app.example.com'
                SubjectAlternativeNames = @('app.example.com')
                NotAfter                = if ($id -eq 'old-def') { [DateTime]::UtcNow.AddDays(-30) } else { [DateTime]'2099-01-01' }
            }
        }
        $results = @(Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Confirm:$false -WarningVariable warnings -WarningAction SilentlyContinue)
        $results[0].Action | Should -Be 'NoReplacementFound'
        $warnings | Should -Match 'tie'
        Should -Invoke Edit-ELB2Listener -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'does not change the listener under -WhatIf' {
        $results = @(Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -WhatIf)
        $results[0].Action | Should -Be 'Skipped'
        $results[0].ReplacementCertificateArn | Should -BeLike '*/exact'
        Should -Invoke Edit-ELB2Listener -ModuleName ELB-Customizations -Times 0 -Exactly
        Should -Invoke Remove-ELB2ListenerCertificate -ModuleName ELB-Customizations -Times 0 -Exactly
    }

    It 'searches for replacements in the expired certificate region' {
        $null = Remove-CHARExpiredELBListenerCertificate -ReplaceDefaultCertificate -Region eu-west-1 -Confirm:$false
        Should -Invoke Get-ACMCertificateList -ModuleName ELB-Customizations -Times 1 -Exactly -ParameterFilter {
            $Region -eq 'us-east-1' -and $CertificateStatus -eq 'ISSUED'
        }
    }

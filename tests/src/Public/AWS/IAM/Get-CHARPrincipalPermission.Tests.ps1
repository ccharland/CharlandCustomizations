                    $denyCount = Get-Random -Minimum 1 -Maximum 4
                    $statements = @()
                    $statements += 1..$allowCount | ForEach-Object { [ordered]@{ Effect = 'Allow'; Action = 'svc:DoThing'; Resource = '*' } }
                    $statements += 1..$denyCount | ForEach-Object { [ordered]@{ Effect = 'Deny'; Action = 'svc:DoThing'; Resource = '*' } }

                    $doc = [ordered]@{ Version = '2012-10-17'; Statement = @($statements) }
                    $enc = [System.Web.HttpUtility]::UrlEncode(($doc | ConvertTo-Json -Depth 10))

                    Mock Get-IAMAttachedRolePolicyList { [PSCustomObject]@{ PolicyName = 'm'; PolicyArn = 'arn:aws:iam::123456789012:policy/m' } }
                    Mock Get-IAMPolicy { [PSCustomObject]@{ DefaultVersionId = 'v1' } }
                    Mock Get-IAMPolicyVersion { [PSCustomObject]@{ Document = $enc } }
                    Mock Get-IAMRolePolicyList { @() }

                    $arn = 'arn:aws:iam::123456789012:role/effect-role'

                    # -Effect Deny -> only Deny records.
                    $denyOnly = @(Get-CHARPrincipalPermission -PrincipalArn $arn -Action 'svc:DoThing' -Effect Deny)
                    $denyOnly.Count | Should -Be $denyCount -Because "Iteration $i Deny filter returns only the Deny matches"
                    ($denyOnly | Where-Object { $_.Effect -ne 'Deny' }).Count | Should -Be 0

                    # -Effect Allow -> Allow records PLUS all Deny records (Deny always surfaced).
                    $allowFilter = @(Get-CHARPrincipalPermission -PrincipalArn $arn -Action 'svc:DoThing' -Effect Allow)
                    ($allowFilter | Where-Object { $_.Effect -eq 'Allow' }).Count | Should -Be $allowCount
                    ($allowFilter | Where-Object { $_.Effect -eq 'Deny' }).Count | Should -Be $denyCount -Because "Iteration $i Allow filter still surfaces all Deny (Req 4.3)"

                    # Unset -> both effects.
                    $both = @(Get-CHARPrincipalPermission -PrincipalArn $arn -Action 'svc:DoThing')
                    $both.Count | Should -Be ($allowCount + $denyCount) -Because "Iteration $i unset filter returns both effects"
                }
            }
        }
    }

    Context 'Property: Effective-access verdict precedence' {
        # Feature: iam-permission-role-auditing, Property 10: Effective-access verdict precedence
        # Validates: Requirements 5.1, 5.2, 5.3, 5.4, 6.4

        It 'Deny beats Allow; Allow when only allow; ImplicitDeny when no match over 100 iterations' {
            InModuleScope IAM-Customizations {
                # Encodes a policy document from a set of statement hashtables. A script-scoped
                # variable holds the current document so the single Get-IAMPolicyVersion mock
                # (registered once, in the It's own scope) returns whatever each iteration sets.
                $script:VerdictDoc = $null
                Mock Get-IAMAttachedRolePolicyList { [PSCustomObject]@{ PolicyName = 'm'; PolicyArn = 'arn:aws:iam::123456789012:policy/m' } }
                Mock Get-IAMPolicy { [PSCustomObject]@{ DefaultVersionId = 'v1' } }
                Mock Get-IAMPolicyVersion { [PSCustomObject]@{ Document = $script:VerdictDoc } }
                Mock Get-IAMRolePolicyList { @() }

                function ConvertTo-EncodedDoc {
                    param([object[]]$Statements)
                    $doc = [ordered]@{ Version = '2012-10-17'; Statement = @($Statements) }
                    [System.Web.HttpUtility]::UrlEncode(($doc | ConvertTo-Json -Depth 10))
                }

                $arn = 'arn:aws:iam::123456789012:role/verdict-role'

                foreach ($i in 1..100) {
                    # Case 1: a matching Deny coexists with a matching Allow -> Deny wins.
                    $script:VerdictDoc = ConvertTo-EncodedDoc -Statements @(
                        [ordered]@{ Effect = 'Allow'; Action = 'svc:DoThing'; Resource = '*' },
                        [ordered]@{ Effect = 'Deny'; Action = 'svc:DoThing'; Resource = '*' }
                    )
                    $r1 = @(Get-CHARPrincipalPermission -PrincipalArn $arn -Action 'svc:DoThing')
                    ($r1 | Select-Object -First 1).Verdict | Should -Be 'Deny' -Because "Iteration $i Deny must beat Allow"

                    # Case 2: only Allow matches -> Allow.
                    $script:VerdictDoc = ConvertTo-EncodedDoc -Statements @(
                        [ordered]@{ Effect = 'Allow'; Action = 'svc:DoThing'; Resource = '*' }
                    )
                    $r2 = @(Get-CHARPrincipalPermission -PrincipalArn $arn -Action 'svc:DoThing')
                    ($r2 | Select-Object -First 1).Verdict | Should -Be 'Allow' -Because "Iteration $i Allow-only yields Allow"

                    # Case 3: nothing matches the query -> ImplicitDeny (no matched statements ->
                    # no records emitted, so assert the empty display set for the queried action).
                    $script:VerdictDoc = ConvertTo-EncodedDoc -Statements @(
                        [ordered]@{ Effect = 'Allow'; Action = 'other:Action'; Resource = '*' }
                    )
                    $r3 = @(Get-CHARPrincipalPermission -PrincipalArn $arn -Action 'svc:DoThing')
                    $r3.Count | Should -Be 0 -Because "Iteration $i no statement matches the query"
                }
            }
        }
    }


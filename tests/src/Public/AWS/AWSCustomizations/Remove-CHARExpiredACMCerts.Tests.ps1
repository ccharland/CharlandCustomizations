Describe 'Remove-CHARExpiredACMCerts' -Tag 'Unit' {
    BeforeEach {
        Mock Test-CHARAWSCmdlet { $true } -ModuleName ACM-Customizations
        Mock Remove-ACMCertificate -ModuleName ACM-Customizations { }
        Mock Get-ACMCertificateList -ModuleName ACM-Customizations {
            @(
                [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/old-aaa' }
                [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/recent-bbb' }
                [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/inuse-ccc' }
                [PSCustomObject]@{ CertificateArn = 'arn:aws:acm:us-east-1:123456789012:certificate/nodate-ddd' }
            )
        }
        Mock Get-ACMCertificateDetail -ModuleName ACM-Customizations {
            $notAfter = switch -Wildcard ($CertificateArn) {
                '*/old-aaa'    { [DateTime]::UtcNow.AddDays(-200) }
                '*/recent-bbb' { [DateTime]::UtcNow.AddDays(-10) }
                '*/inuse-ccc'  { [DateTime]::UtcNow.AddDays(-300) }
                default        { [DateTime]::MinValue }
            }
            [PSCustomObject]@{
                CertificateArn = $CertificateArn
                DomainName     = 'test.example'
                NotAfter       = $notAfter
                InUseBy        = if ($CertificateArn -like '*/inuse-ccc') { @('arn:aws:elasticloadbalancing:x') } else { @() }
            }
        }
    }

    It 'queries only EXPIRED certificates' {
        $null = Remove-CHARExpiredACMCerts -Confirm:$false -WarningAction SilentlyContinue
        Should -Invoke Get-ACMCertificateList -ModuleName ACM-Customizations -Times 1 -Exactly -ParameterFilter {
            $CertificateStatus -eq 'EXPIRED'
        }
    }

    It 'deletes every unused expired certificate with a known expiry by default' {
        $results = @(Remove-CHARExpiredACMCerts -Confirm:$false -WarningAction SilentlyContinue)
        $results.CertificateId | Should -Be @('old-aaa', 'recent-bbb')
        $results.Action | Should -Not -Contain 'Skipped'
        Should -Invoke Remove-ACMCertificate -ModuleName ACM-Customizations -Times 2 -Exactly
    }

    It 'honors -DaysExpired as a minimum age' {
        $results = @(Remove-CHARExpiredACMCerts -DaysExpired 90 -Confirm:$false -WarningAction SilentlyContinue)
        $results.Count | Should -Be 1
        $results[0].CertificateId | Should -Be 'old-aaa'
        $results[0].DaysSinceExpired | Should -BeGreaterOrEqual 199
        Should -Invoke Remove-ACMCertificate -ModuleName ACM-Customizations -Times 1 -Exactly -ParameterFilter {
            $CertificateArn -like '*/old-aaa'
        }
    }

    It 'matches -CertId with wildcards' {
        $results = @(Remove-CHARExpiredACMCerts -CertId 'rec*' -Confirm:$false -WarningAction SilentlyContinue)
        $results.CertificateId | Should -Be @('recent-bbb')
    }

    It 'accepts a full ARN for -CertId' {
        $arn = 'arn:aws:acm:us-east-1:123456789012:certificate/old-aaa'
        $results = @(Remove-CHARExpiredACMCerts -CertId $arn -Confirm:$false -WarningAction SilentlyContinue)
        $results.CertificateId | Should -Be @('old-aaa')
    }

    It 'returns nothing and deletes nothing when -CertId matches no certificate' {
        $results = @(Remove-CHARExpiredACMCerts -CertId 'zzz*' -Confirm:$false)
        $results.Count | Should -Be 0
        Should -Invoke Remove-ACMCertificate -ModuleName ACM-Customizations -Times 0 -Exactly
    }

    It 'skips certificates that are still in use and warns' {
        $null = Remove-CHARExpiredACMCerts -CertId 'inuse*' -Confirm:$false -WarningVariable warnings -WarningAction SilentlyContinue
        $warnings | Should -Match 'still in use'
        Should -Invoke Remove-ACMCertificate -ModuleName ACM-Customizations -Times 0 -Exactly
    }

    It 'skips certificates with no expiration date and warns' {
        $null = Remove-CHARExpiredACMCerts -CertId 'nodate*' -Confirm:$false -WarningVariable warnings -WarningAction SilentlyContinue
        $warnings | Should -Match 'expiration date is unavailable'
        Should -Invoke Remove-ACMCertificate -ModuleName ACM-Customizations -Times 0 -Exactly
    }

    It 'does not delete under -WhatIf and reports Action Skipped' {
        $results = @(Remove-CHARExpiredACMCerts -CertId 'old*' -WhatIf)
        $results.Count | Should -Be 1
        $results[0].Action | Should -Be 'Skipped'
        Should -Invoke Remove-ACMCertificate -ModuleName ACM-Customizations -Times 0 -Exactly
    }

    It 'rejects a negative -DaysExpired' {
        { Remove-CHARExpiredACMCerts -DaysExpired -1 } | Should -Throw
    }

    It 'surfaces a terminating error when deletion fails' {
        Mock Remove-ACMCertificate -ModuleName ACM-Customizations { throw 'AccessDenied' }
        { Remove-CHARExpiredACMCerts -CertId 'old*' -Confirm:$false } | Should -Throw '*AccessDenied*'
    }
}

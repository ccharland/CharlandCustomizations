Describe 'Resolve-CHARPrincipalArn' -Tag 'Unit' {

    Context 'Valid ARNs' {

        It 'Parses a role ARN correctly' {
            $result = Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::123456789012:role/MyRole'

            $result.Type | Should -Be 'Role'
            $result.Name | Should -Be 'MyRole'
        }

        It 'Parses a user ARN correctly' {
            $result = Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::123456789012:user/jsmith'

            $result.Type | Should -Be 'User'
            $result.Name | Should -Be 'jsmith'
        }

        It 'Parses a group ARN correctly' {
            $result = Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::123456789012:group/Admins'

            $result.Type | Should -Be 'Group'
            $result.Name | Should -Be 'Admins'
        }

        It 'Strips path segments and returns only the name' {
            $result = Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::123456789012:role/app/env/read-only'

            $result.Type | Should -Be 'Role'
            $result.Name | Should -Be 'read-only'
        }

        It 'Handles single path segment before name' {
            $result = Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::111111111111:user/service-accounts/svc-deploy'

            $result.Type | Should -Be 'User'
            $result.Name | Should -Be 'svc-deploy'
        }
    }

    Context 'Invalid ARNs' {

        It 'Throws for malformed ARN missing resource type' {
            { Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::123456789012:MyRole' } |
                Should -Throw '*Invalid IAM principal ARN*'
        }

        It 'Throws for non-IAM service ARN' {
            { Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:s3:::my-bucket' } |
                Should -Throw '*Invalid IAM principal ARN*'
        }

        It 'Throws for unsupported IAM resource type (policy)' {
            { Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::123456789012:policy/MyPolicy' } |
                Should -Throw '*Invalid IAM principal ARN*'
        }

        It 'Throws for ARN with invalid account ID length' {
            { Resolve-CHARPrincipalArn -PrincipalArn 'arn:aws:iam::12345:role/MyRole' } |
                Should -Throw '*Invalid IAM principal ARN*'
        }
    }
}


            Get-CHARPrincipalPolicyDocument -PrincipalType 'User' -PrincipalName 'TestUser' -AwsParams @{}

            Should -Invoke Get-IAMAttachedUserPolicyList -Times 1
            Should -Invoke Get-IAMUserPolicyList -Times 1
        }
    }

    Context 'Group enumeration' {

        It 'Calls group-specific cmdlets for Group principal type' {
            Get-CHARPrincipalPolicyDocument -PrincipalType 'Group' -PrincipalName 'TestGroup' -AwsParams @{}

            Should -Invoke Get-IAMAttachedGroupPolicyList -Times 1
            Should -Invoke Get-IAMGroupPolicyList -Times 1
        }
    }

    Context 'Statement normalization' {

        BeforeAll {
            # URL-encoded policy document with a single statement
            $encodedDoc = [System.Web.HttpUtility]::UrlEncode('{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Action":"s3:GetObject","Resource":"*"}]}')

            Mock Get-IAMAttachedRolePolicyList {
                @([PSCustomObject]@{ PolicyArn = 'arn:aws:iam::123456789012:policy/TestPolicy'; PolicyName = 'TestPolicy' })
            }
            Mock Get-IAMPolicy {
                [PSCustomObject]@{ DefaultVersionId = 'v1' }
            }
            Mock Get-IAMPolicyVersion {
                [PSCustomObject]@{ Document = $encodedDoc }
            }
            Mock Get-IAMRolePolicyList { @() }
        }

        It 'Emits statement records with correct properties' {
            $result = @(Get-CHARPrincipalPolicyDocument -PrincipalType 'Role' -PrincipalName 'TestRole' -AwsParams @{})

            $result | Should -HaveCount 1
            $result[0].PolicyName | Should -Be 'TestPolicy'
            $result[0].PolicyType | Should -Be 'Managed'
            $result[0].Effect | Should -Be 'Allow'
            $result[0].Action | Should -Contain 's3:GetObject'
            $result[0].Resource | Should -Contain '*'
        }
    }

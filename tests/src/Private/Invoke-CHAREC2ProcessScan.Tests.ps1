        Import-Module AWS.Tools.Common, AWS.Tools.SimpleSystemsManagement -ErrorAction Stop
    }
    . "$PSScriptRoot/../../../src/CharlandCustomizations/Private/Invoke-CHAREC2ProcessScan.ps1"

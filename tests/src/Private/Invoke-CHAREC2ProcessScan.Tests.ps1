Describe 'Invoke-CHAREC2ProcessScan' -Tag 'Unit' {
    BeforeEach {
        $script:fleet = @{
            'i-0aaaaaaaa' = [PSCustomObject]@{ InstanceId = 'i-0aaaaaaaa'; PlatformType = 'Linux'; PingStatus = 'Online' }
            'i-0bbbbbbbb' = [PSCustomObject]@{ InstanceId = 'i-0bbbbbbbb'; PlatformType = 'Windows'; PingStatus = 'Online' }
            'i-0eeeeeeee' = [PSCustomObject]@{ InstanceId = 'i-0eeeeeeee'; PlatformType = 'Linux'; PingStatus = 'ConnectionLost' }
        }
        Mock Start-Sleep { }
        Mock Get-SSMInstanceInformation {
            foreach ($id in $Filter.Values) { if ($script:fleet.ContainsKey($id)) { $script:fleet[$id] } }
        }
        Mock Send-SSMCommand { [PSCustomObject]@{ CommandId = 'c' } }
        Mock Get-SSMCommandInvocation {
            $text = if ($InstanceId -eq 'i-0aaaaaaaa') { "nginx`n" } else { "W3WP`r`n" }
            [PSCustomObject]@{
                Status         = [PSCustomObject]@{ Value = 'Success' }
                CommandPlugins = @([PSCustomObject]@{ Output = $text })
            }
        }
    }
    It 'returns Requested and Found for each instance that was checked' {
        $r = Invoke-CHAREC2ProcessScan -InstanceId i-0aaaaaaaa, i-0bbbbbbbb `
            -LinuxProcess nginx, java -WindowsProcess w3wp.exe
        $linux = $r | Where-Object InstanceId -eq 'i-0aaaaaaaa'
        $linux.Requested | Should -Be @('nginx', 'java')
        $linux.Found | Should -Be @('nginx')
        $windows = $r | Where-Object InstanceId -eq 'i-0bbbbbbbb'
        $windows.Requested | Should -Be @('w3wp')
        $windows.Found | Should -Be @('w3wp')
    }
    It 'omits instances that are not SSM online' {
        $r = Invoke-CHAREC2ProcessScan -InstanceId i-0eeeeeeee, i-0cccccccc -LinuxProcess nginx 3>$null
        $r | Should -BeNullOrEmpty
    }
    It 'omits instances whose command did not succeed' {
        Mock Get-SSMCommandInvocation {
            [PSCustomObject]@{ Status = [PSCustomObject]@{ Value = 'TimedOut' }; CommandPlugins = @() }
        }
        Invoke-CHAREC2ProcessScan -InstanceId i-0aaaaaaaa -LinuxProcess nginx 3>$null | Should -BeNullOrEmpty
    }
    It 'sends no command for a platform without a process list' {
        Invoke-CHAREC2ProcessScan -InstanceId i-0aaaaaaaa, i-0bbbbbbbb -LinuxProcess nginx | Out-Null
        Should -Invoke Send-SSMCommand -Times 1 -Exactly -ParameterFilter { $DocumentName -eq 'AWS-RunShellScript' }
    }
    It 'sends batches of at most 50 instances' {
        $ids = 1..120 | ForEach-Object { 'i-{0:x9}' -f $_ }
        foreach ($id in $ids) {
            $script:fleet[$id] = [PSCustomObject]@{ InstanceId = $id; PlatformType = 'Linux'; PingStatus = 'Online' }
        }
        Invoke-CHAREC2ProcessScan -InstanceId $ids -LinuxProcess nginx | Out-Null
        Should -Invoke Send-SSMCommand -Times 3 -Exactly
        Should -Invoke Send-SSMCommand -Times 0 -ParameterFilter { @($InstanceId).Count -gt 50 }
    }
    It 'passes AwsParam values to the SSM cmdlets' {
        Invoke-CHAREC2ProcessScan -InstanceId i-0aaaaaaaa -LinuxProcess nginx -AwsParam @{ Region = 'eu-west-1' } | Out-Null
        Should -Invoke Send-SSMCommand -ParameterFilter { $Region -eq 'eu-west-1' }
        Should -Invoke Get-SSMInstanceInformation -ParameterFilter { $Region -eq 'eu-west-1' }
    }

Describe 'Resolve-CHARKMSKeyArn' -Tag 'Unit' {
    It 'Splits a key ARN into region, account and key ID' {
        $r = Resolve-CHARKMSKeyArn -KeyArn 'arn:aws:kms:eu-west-1:123456789012:key/1234abcd-12ab-34cd-56ef-1234567890ab'
        $r.Region | Should -Be 'eu-west-1'
        $r.Account | Should -Be '123456789012'
        $r.KeyId | Should -Be '1234abcd-12ab-34cd-56ef-1234567890ab'
    }

    It 'Accepts multi-Region key IDs' {
        (Resolve-CHARKMSKeyArn -KeyArn 'arn:aws:kms:us-east-1:123456789012:key/mrk-1234abcd12ab34cd56ef1234567890ab').KeyId | Should -Be 'mrk-1234abcd12ab34cd56ef1234567890ab'
    }

    It 'Rejects alias ARNs and malformed input' {
        { Resolve-CHARKMSKeyArn -KeyArn 'arn:aws:kms:us-east-1:123456789012:alias/app' } | Should -Throw '*Invalid KMS key ARN*'
        { Resolve-CHARKMSKeyArn -KeyArn 'nope' } | Should -Throw '*Invalid KMS key ARN*'
    }
}

Describe 'Get-CHARKMSConfigStringValue' -Tag 'Unit' {
    It 'Flattens nested objects and arrays into path/value pairs' {
        $obj = '{"a":{"b":"x","c":["y","z"]},"n":5}' | ConvertFrom-Json
        $r = @(Get-CHARKMSConfigStringValue -InputObject $obj -Path 'configuration')
        $r.Count | Should -Be 3
        ($r | Where-Object Value -eq 'x').Path | Should -Be 'configuration.a.b'
    }

    It 'Returns nothing for null input' {
        @(Get-CHARKMSConfigStringValue -InputObject $null -Path 'p').Count | Should -Be 0
    }
}

BeforeAll {
    . "$PSScriptRoot/../../../src/CharlandCustomizations/Public/PowerShell/ConvertTo-CHARHashtable.ps1"
}

Describe 'ConvertTo-CHARHashtable' -Tag 'Unit' {

    Context 'Basic conversion' {

        It 'Converts a PSCustomObject to a hashtable with matching keys and values' {
            # Arrange
            $obj = [pscustomobject]@{ Name = 'web-1'; Port = 443 }

            # Act
            $result = ConvertTo-CHARHashtable -InputObject $obj

            # Assert
            $result.Keys.Count | Should -Be 2
            $result['Name'] | Should -Be 'web-1'
            $result['Port'] | Should -Be 443
        }

        It 'Preserves exact key casing from the source object' {
            $obj = [pscustomobject]@{ InstanceType = 't3.micro' }
            $result = ConvertTo-CHARHashtable -InputObject $obj
            $result.Keys | Should -Contain 'InstanceType'
        }

        It 'Includes properties whose value is $null' {
            $obj = [pscustomobject]@{ Name = 'x'; Optional = $null }
            $result = ConvertTo-CHARHashtable -InputObject $obj
            $result.Contains('Optional') | Should -BeTrue
            $result['Optional'] | Should -BeNullOrEmpty
        }

        It 'Returns an empty hashtable for an object with zero properties' {
            $obj = [pscustomobject]@{}
            $result = ConvertTo-CHARHashtable -InputObject $obj
            $result.Keys.Count | Should -Be 0
        }
    }

    Context 'Value type fidelity' {

        It 'Preserves the value type of each property' {
            $obj = [pscustomobject]@{ Count = [int]5; Enabled = [bool]$true }
            $result = ConvertTo-CHARHashtable -InputObject $obj
            $result['Count'].GetType().Name | Should -Be 'Int32'
            $result['Enabled'].GetType().Name | Should -Be 'Boolean'
        }

        It 'Round-trips back to an equivalent PSCustomObject' {
            $obj = [pscustomobject]@{ A = 1; B = 'two'; C = $true }
            $result = ConvertTo-CHARHashtable -InputObject $obj
            $rebuilt = [pscustomobject]$result
            $rebuilt.A | Should -Be $obj.A
            $rebuilt.B | Should -Be $obj.B
            $rebuilt.C | Should -Be $obj.C
        }
    }

    Context 'Pipeline input' {

        It 'Produces equivalent output for pipeline and parameter-bound input' {
            $obj = [pscustomobject]@{ Name = 'a'; Value = 1 }
            $bound = ConvertTo-CHARHashtable -InputObject $obj
            $piped = $obj | ConvertTo-CHARHashtable
            $piped['Name'] | Should -Be $bound['Name']
            $piped['Value'] | Should -Be $bound['Value']
        }

        It 'Streams one hashtable per object in input order' {
            $objects = @(
                [pscustomobject]@{ Id = 1 }
                [pscustomobject]@{ Id = 2 }
                [pscustomobject]@{ Id = 3 }
            )
            $results = $objects | ConvertTo-CHARHashtable
            $results.Count | Should -Be 3
            $results[0]['Id'] | Should -Be 1
            $results[1]['Id'] | Should -Be 2
            $results[2]['Id'] | Should -Be 3
        }
    }

    Context 'Property inclusion filter' {

        It 'Returns only the named properties' {
            $obj = [pscustomobject]@{ Name = 'x'; Port = 80; Extra = 'drop' }
            $result = ConvertTo-CHARHashtable -InputObject $obj -Property Name, Port
            $result.Keys.Count | Should -Be 2
            $result.Contains('Name') | Should -BeTrue
            $result.Contains('Port') | Should -BeTrue
            $result.Contains('Extra') | Should -BeFalse
        }

        It 'Matches property names case-insensitively but preserves source casing' {
            $obj = [pscustomobject]@{ InstanceType = 't3.micro' }
            $result = ConvertTo-CHARHashtable -InputObject $obj -Property 'instancetype'
            $result.Keys | Should -Contain 'InstanceType'
            $result['InstanceType'] | Should -Be 't3.micro'
        }

        It 'Silently omits requested properties that do not exist' {
            $obj = [pscustomobject]@{ Name = 'x' }
            $result = ConvertTo-CHARHashtable -InputObject $obj -Property Name, DoesNotExist
            $result.Keys.Count | Should -Be 1
            $result.Contains('Name') | Should -BeTrue
        }

        It 'Returns an empty hashtable when -Property is an empty array' {
            $obj = [pscustomobject]@{ Name = 'x'; Port = 80 }
            $result = ConvertTo-CHARHashtable -InputObject $obj -Property @()
            $result.Keys.Count | Should -Be 0
        }
    }

    Context 'Property exclusion filter' {

        It 'Omits the excluded properties' {
            $obj = [pscustomobject]@{ Name = 'x'; Secret = 'hunter2'; Port = 80 }
            $result = ConvertTo-CHARHashtable -InputObject $obj -ExcludeProperty Secret
            $result.Contains('Secret') | Should -BeFalse
            $result.Keys.Count | Should -Be 2
        }

        It 'Applies exclusion after inclusion when both are supplied' {
            $obj = [pscustomobject]@{ Name = 'x'; Port = 80; Secret = 's' }
            $result = ConvertTo-CHARHashtable -InputObject $obj -Property Name, Port, Secret -ExcludeProperty Secret
            $result.Keys.Count | Should -Be 2
            $result.Contains('Secret') | Should -BeFalse
        }

        It 'Returns an empty hashtable when all properties are excluded' {
            $obj = [pscustomobject]@{ A = 1; B = 2 }
            $result = ConvertTo-CHARHashtable -InputObject $obj -ExcludeProperty A, B
            $result.Keys.Count | Should -Be 0
        }
    }

    Context 'Nested object handling' {

        It 'Leaves nested PSCustomObjects unconverted at default depth' {
            $child = [pscustomobject]@{ Inner = 'value' }
            $obj = [pscustomobject]@{ Name = 'x'; Child = $child }
            $result = ConvertTo-CHARHashtable -InputObject $obj
            $result['Child'] | Should -BeOfType [System.Management.Automation.PSCustomObject]
        }

        It 'Recursively converts nested PSCustomObjects when -Depth is greater than 1' {
            $child = [pscustomobject]@{ Inner = 'value' }
            $obj = [pscustomobject]@{ Name = 'x'; Child = $child }
            $result = ConvertTo-CHARHashtable -InputObject $obj -Depth 2
            $result['Child'] | Should -BeOfType [System.Collections.Specialized.OrderedDictionary]
            $result['Child']['Inner'] | Should -Be 'value'
        }
    }

    Context 'Error and edge-case handling' {

        It 'Writes a warning and produces no output for $null input' {
            $warnings = ConvertTo-CHARHashtable -InputObject $null 3>&1
            $warnings | Should -Not -BeNullOrEmpty
            ($warnings | Out-String) | Should -Match 'null'
        }

        It 'Writes a non-terminating error for a non-PSCustomObject type' {
            $err = $null
            $result = ConvertTo-CHARHashtable -InputObject 'just a string' -ErrorVariable err -ErrorAction SilentlyContinue
            $err | Should -Not -BeNullOrEmpty
            $err[0].Exception.Message | Should -Match 'PSCustomObject'
            $result | Should -BeNullOrEmpty
        }

        It 'Continues processing valid items after an invalid one in a pipeline' {
            $mixed = @(
                [pscustomobject]@{ Id = 1 }
                42
                [pscustomobject]@{ Id = 3 }
            )
            $err = $null
            $results = $mixed | ConvertTo-CHARHashtable -ErrorVariable err -ErrorAction SilentlyContinue
            $results.Count | Should -Be 2
            $results[0]['Id'] | Should -Be 1
            $results[1]['Id'] | Should -Be 3
            $err | Should -Not -BeNullOrEmpty
        }
    }
}
